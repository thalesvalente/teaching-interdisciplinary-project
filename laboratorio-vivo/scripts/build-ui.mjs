#!/usr/bin/env node
// Generates Apps Script HTML from the same audited frontend sources. No external dependencies.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFileSync(path.join(root,'frontend',name),'utf8');
const banner='<!-- Generated by scripts/build-ui.mjs. Edit frontend sources, then rebuild. -->\n';
const index=read('index.html')
  .replace('<meta charset="utf-8">','<meta charset="utf-8">\n  <base target="_top">')
  .replace('<link rel="stylesheet" href="styles.css">',"<?!= include_('Styles'); ?>")
  .replace('  <script src="deployment.js"></script>\n  <script src="lib.js"></script>\n  <script src="app.js"></script>',"  <?!= include_('Client'); ?>");
if(index.includes('src="app.js"')||index.includes('href="styles.css"'))throw new Error('Expected frontend includes were not replaced.');
// There is no deployment URL in the server UI. Its connection is google.script.run.
const code=read('lib.js')+'\n'+read('app.js');
const outputs={
  'Index.html':banner+index,
  'Styles.html':banner+'<style>\n'+read('styles.css')+'\n</style>\n',
  'Client.html':banner+'<script>\n'+code.replace(/<\/script/gi,'<\\/script')+'\n</script>\n'
};
if(process.argv.includes('--check')){
  const different=Object.entries(outputs).filter(([name,content])=>{
    const file=path.join(root,'apps-script',name);return !fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content;
  }).map(([name])=>name);
  if(different.length)throw new Error('Generated UI differs: '+different.join(', ')+'. Run node scripts/build-ui.mjs.');
  process.stdout.write('Generated Apps Script UI is byte-identical to frontend sources.\n');
}else{
  fs.mkdirSync(path.join(root,'apps-script'),{recursive:true});
  for(const [name,content] of Object.entries(outputs))fs.writeFileSync(path.join(root,'apps-script',name),content);
  process.stdout.write('Generated Index.html, Styles.html and Client.html from shared frontend sources.\n');
}
